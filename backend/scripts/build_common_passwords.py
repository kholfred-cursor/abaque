#!/usr/bin/env python3
"""Build the common passwords list for Abaque.

Reads a large password list (SecLists, MIT license), keeps entries of
12 characters or more, deduplicates in lowercase, keeps the first 10,000
(the source is ordered by frequency), and writes the result to
app/core/data/common_passwords.txt.

Source: https://github.com/danielmiessler/SecLists
File:   Passwords/Common-Credentials/xato-net-10-million-passwords-1000000.txt
License: MIT (https://github.com/danielmiessler/SecLists/blob/master/LICENSE)

Usage:
    python scripts/build_common_passwords.py /path/to/xato-net-10-million-passwords-1000000.txt

Exits with code 1 (and writes nothing) if fewer than 10,000 entries are found.
"""

from __future__ import annotations

import sys
from pathlib import Path

MIN_LENGTH = 12
TARGET_COUNT = 10_000
OUTPUT = Path(__file__).parent.parent / "app" / "core" / "data" / "common_passwords.txt"

HEADER = """\
# Common passwords list for Abaque
# Source: SecLists — Passwords/Common-Credentials/xato-net-10-million-passwords-1000000.txt
# License: MIT (https://github.com/danielmiessler/SecLists/blob/master/LICENSE)
# Filtered: >= {min_len} characters, deduplicated (lowercase), first {count} entries by frequency.
# Generated by: backend/scripts/build_common_passwords.py
# DO NOT EDIT — regenerate with the script above.
"""


def main() -> None:
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} <path-to-seclists-password-file>", file=sys.stderr)
        sys.exit(1)

    source_path = Path(sys.argv[1])
    if not source_path.exists():
        print(f"File not found: {source_path}", file=sys.stderr)
        sys.exit(1)

    seen: set[str] = set()
    passwords: list[str] = []

    with source_path.open(encoding="utf-8", errors="ignore") as f:
        for line in f:
            pwd = line.strip()
            if len(pwd) < MIN_LENGTH:
                continue
            lower = pwd.lower()
            if lower not in seen:
                seen.add(lower)
                passwords.append(lower)
            if len(passwords) >= TARGET_COUNT:
                break

    if len(passwords) < TARGET_COUNT:
        print(
            f"ERROR: only {len(passwords)} passwords found with >= {MIN_LENGTH} chars. "
            f"Expected {TARGET_COUNT}. Use a larger source file.",
            file=sys.stderr,
        )
        sys.exit(1)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8") as f:
        f.write(HEADER.format(min_len=MIN_LENGTH, count=len(passwords)))
        for pwd in passwords:
            f.write(pwd + "\n")

    print(f"Wrote {len(passwords)} passwords to {OUTPUT}")


if __name__ == "__main__":
    main()
